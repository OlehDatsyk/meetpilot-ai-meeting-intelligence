import { AlertTriangle, CalendarDays, HelpCircle, Info, ListChecks, MessageSquare, Route } from "lucide-react";
import type { ReactNode } from "react";
import { formatDate } from "../lib/format";
import { Card, CardHeader } from "./ui";

interface Cited { text: string; segment_ids: string[] }
export interface SummaryLike {
  executive_summary: string;
  discussion_points: { topic: string; summary: string; segment_ids: string[] }[];
  open_questions: Cited[];
  risks: Cited[];
  follow_ups: Cited[];
  key_dates: { date_text: string; date: string | null; interpreted: boolean; description: string; segment_ids: string[] }[];
  grounding_notes: string[];
  provider?: string;
  model?: string | null;
  created_at?: string;
}

function SourceLink({ ids, onJump }: { ids: string[]; onJump?: (id: string) => void }) {
  if (!ids.length || !onJump) return null;
  return (
    <button onClick={() => onJump(ids[0])} className="ml-1.5 whitespace-nowrap text-xs font-medium text-accent hover:underline" title="Show in transcript">
      source
    </button>
  );
}

function Section({ title, icon, children, empty }: { title: string; icon: ReactNode; children: ReactNode; empty?: boolean }) {
  return (
    <Card>
      <CardHeader title={<span className="inline-flex items-center gap-2">{icon}{title}</span>} />
      <div className="px-5 py-4 text-sm">{empty ? <p className="text-muted">None mentioned.</p> : children}</div>
    </Card>
  );
}

export function SummaryView({ s, onJump }: { s: SummaryLike; onJump?: (segmentId: string) => void }) {
  return (
    <div className="space-y-5">
      <Card className="p-5">
        <h2 className="text-xs font-semibold uppercase tracking-wide text-muted">Executive summary</h2>
        <p className="mt-2 text-[15px] leading-relaxed text-slate-800">{s.executive_summary}</p>
        {s.provider && <p className="mt-3 text-xs text-muted">Generated by {s.provider}{s.model ? ` / ${s.model}` : ""}{s.created_at ? ` on ${formatDate(s.created_at)}` : ""}. AI output can contain mistakes; check the linked sources.</p>}
      </Card>
      <div className="grid gap-5 lg:grid-cols-2">
        <Section title="Main discussion points" icon={<MessageSquare className="size-4 text-slate-400" />} empty={!s.discussion_points.length}>
          <ul className="space-y-2.5">
            {s.discussion_points.map((p, i) => (
              <li key={i}><span className="font-medium text-ink">{p.topic}</span>{p.summary && <span className="text-slate-600"> — {p.summary}</span>}<SourceLink ids={p.segment_ids} onJump={onJump} /></li>
            ))}
          </ul>
        </Section>
        <Section title="Key dates" icon={<CalendarDays className="size-4 text-slate-400" />} empty={!s.key_dates.length}>
          <ul className="space-y-2.5">
            {s.key_dates.map((k, i) => (
              <li key={i}>
                <span className="font-medium">“{k.date_text}”</span>
                {k.date && <span className="text-slate-600"> · {formatDate(k.date)}{k.interpreted && <span className="text-amber-700"> (interpreted, confirm)</span>}</span>}
                <span className="block text-slate-600">{k.description}<SourceLink ids={k.segment_ids} onJump={onJump} /></span>
              </li>
            ))}
          </ul>
        </Section>
        <Section title="Open questions" icon={<HelpCircle className="size-4 text-slate-400" />} empty={!s.open_questions.length}>
          <ul className="list-disc space-y-1.5 pl-4">{s.open_questions.map((q, i) => <li key={i}>{q.text}<SourceLink ids={q.segment_ids} onJump={onJump} /></li>)}</ul>
        </Section>
        <Section title="Risks and blockers" icon={<AlertTriangle className="size-4 text-slate-400" />} empty={!s.risks.length}>
          <ul className="list-disc space-y-1.5 pl-4">{s.risks.map((q, i) => <li key={i}>{q.text}<SourceLink ids={q.segment_ids} onJump={onJump} /></li>)}</ul>
        </Section>
        <Section title="Suggested follow-up" icon={<Route className="size-4 text-slate-400" />} empty={!s.follow_ups.length}>
          <p className="mb-2 text-xs text-muted">Next steps suggested by the AI from the discussion.</p>
          <ul className="list-disc space-y-1.5 pl-4">{s.follow_ups.map((q, i) => <li key={i}>{q.text}<SourceLink ids={q.segment_ids} onJump={onJump} /></li>)}</ul>
        </Section>
        {s.grounding_notes.length > 0 && (
          <Section title="Grounding checks" icon={<ListChecks className="size-4 text-slate-400" />}>
            <p className="mb-2 flex items-start gap-1.5 text-xs text-muted"><Info className="mt-0.5 size-3.5 shrink-0" />MeetPilot AI checked the AI's output against the transcript and corrected these items:</p>
            <ul className="list-disc space-y-1.5 pl-4 text-slate-600">{s.grounding_notes.map((n, i) => <li key={i}>{n}</li>)}</ul>
          </Section>
        )}
      </div>
    </div>
  );
}
